/**
 * THROWAWAY SPIKE preview: turns preview/view-<step>.json (written by
 * run-logic.ts --write) into preview/<step>.slint, a throwaway wrapper that
 * sets the Surface's properties as the shell would (camelCase keys become
 * kebab-case, `{ "$image": file }` becomes @image-url), so slint-viewer can
 * render main.slint without the shell.
 *
 *   bun preview/gen-preview.ts      (from surfaces/zone/)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"

const here = dirname(new URL(import.meta.url).pathname)
const kebab = (key: string) => key.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`)

function literal(value: unknown): string {
  if (typeof value === "string") return JSON.stringify(value)
  if (typeof value === "number" || typeof value === "boolean") return String(value)
  if (Array.isArray(value)) return `[${value.map(literal).join(", ")}]`
  if (value !== null && typeof value === "object") {
    const record = value as Record<string, unknown>
    if (typeof record.$image === "string") return `@image-url(${JSON.stringify(record.$image)})`
    return `{ ${Object.entries(record).filter(([, item]) => item !== null).map(([key, item]) => `${kebab(key)}: ${literal(item)}`).join(", ")} }`
  }
  throw new Error(`no literal for ${String(value)}`)
}

for (const file of readdirSync(here).filter(name => /^view-.*\.json$/.test(name))) {
  const view = JSON.parse(readFileSync(join(here, file), "utf8")) as Record<string, unknown>
  const name = file.replace(/^view-/, "").replace(/\.json$/, "")
  const lines = Object.entries(view)
    .filter(([, value]) => value !== null)
    .map(([key, value]) => `    ${kebab(key)}: ${literal(value)};`)
  const source = [
    "// GENERATED by gen-preview.ts from " + file + ": a throwaway wrapper for slint-viewer.",
    'import { Surface } from "../main.slint";',
    "",
    "export component Preview inherits Surface {",
    ...lines,
    "}",
    "",
  ].join("\n")
  writeFileSync(join(here, `${name}.slint`), source)
  console.log(`wrote preview/${name}.slint`)
}
