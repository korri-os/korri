"""Writes src/measure.ts: the advance of every glyph of Velvet's two faces,
in thousandths of the font size, so the logic can fit a title to a box and
break a line of facts before Slint draws them.

    python3 measure.py ../BigShoulders-ExtraBold.ttf ../Archivo-SemiCondensed.ttf ../Archivo-SemiCondensed-Bold.ttf > ../../src/measure.ts
"""
import sys
from fontTools.ttLib import TTFont


def table(path, name, doc):
    font = TTFont(path)
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    upm = font["head"].unitsPerEm
    rows = []
    for code in sorted(cmap):
        if code < 0x20 or code == 0x7F or (0x80 <= code < 0xA0):
            continue
        rows.append(f"{code}:{round(hmtx[cmap[code]][0] * 1000 / upm)}")
    print(f"/** {doc} Advance per code point, in thousandths of the font size. */")
    print(f"export const {name}: Readonly<Record<number, number>> = {{")
    for i in range(0, len(rows), 12):
        print("  " + ",".join(rows[i:i + 12]) + ",")
    print("}")
    return font


print("// Generated by fonts/source/measure.py from the faces in fonts/. Do not edit.")
display = table(sys.argv[1], "DISPLAY_ADVANCES", "Big Shoulders ExtraBold.")
table(sys.argv[2], "TEXT_ADVANCES", "Archivo semi-condensed.")
table(sys.argv[3], "STRONG_ADVANCES", "Archivo semi-condensed bold.")
upm = display["head"].unitsPerEm
print("/** The display face's ascent, descent and cap height, in thousandths of the font size. */")
print(f"export const DISPLAY_ASCENT = {round(display['hhea'].ascent * 1000 / upm)}")
print(f"export const DISPLAY_DESCENT = {round(-display['hhea'].descent * 1000 / upm)}")
print(f"export const DISPLAY_CAP = {round(display['OS/2'].sCapHeight * 1000 / upm)}")
