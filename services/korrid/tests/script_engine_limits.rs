//! The plugin engine at its resource limits.
//!
//! korrid is long-lived and runs every plugin call inside the korrid process.
//! A call that reaches the heap limit, the stack limit, the deadline or the
//! output budget must end as an ordinary result or error, and the process
//! must keep running. These tests drive korrid's own call path
//! (`call_plugin_operation_bounded`, as acquisition provider turns use it)
//! close to each limit.
//!
//! The regression tests run their work in a child process, so that an
//! abnormal end (a signal, or a call that never returns) is reported as a
//! test failure and not as a dead test runner. With rquickjs 0.9
//! (quickjs-ng 0.8.0) a heap sweep that compiled code ended in SIGSEGV and
//! the backtracking call never stopped. Two tests are ignored only for their run time (about
//! 50 s and 140 s in a debug build); run them with
//! `nix run .#korrid-test -- --test script_engine_limits -- --ignored`.

use std::{
    os::unix::process::ExitStatusExt,
    process::Command,
    time::{Duration, Instant},
};

use korrid::script::{call_plugin_operation_bounded, source::SourceSnapshot};

/// The bound acquisition provider turns use (`acquisition/turns.rs`).
const PROVIDER_INPUT_BOUND: usize = 4 * 1024 * 1024;

/// Set in a child process that runs one regression test's work.
const CHILD: &str = "KORRID_ENGINE_LIMITS_CHILD";

const PLUGIN: &str = r#"
export const name = 'limits';
function depth(n) { return n === 0 ? 0 : 1 + depth(n - 1); }
function mapped(n) { return n === 0 ? 0 : [n].map((x) => 1 + mapped(x - 1))[0]; }
export const handlers = {
  'page.parse': (input) => {
    const text = input.responses[0].text;
    const rows = [];
    for (const m of text.matchAll(/<a[^>]*href="([^"]*)"[^>]*>([^<]*)<\/a>/g)) {
      rows.push({ href: m[1], title: m[2].trim() });
    }
    const words = text.split(/\s+/).filter(w => /^[a-z]+\d*$/i.test(w));
    return { rows: rows.slice(0, 20), count: rows.length, words: words.length };
  },
  'page.backtrack': (input) => ({ hit: /^(\w+\s?)*$/.test(input.responses[0].text) }),
  'items.count': (input) => ({ count: input.items.length }),
  'stack.recurse': (input) => ({ depth: depth(input.depth) }),
  'stack.map': (input) => ({ depth: mapped(input.depth) }),
  'deadline.spin': () => { while (true) {} },
  'heap.hold': (input) => {
    const keep = [];
    for (let i = 0; i < input.blocks; i++) keep.push(new Array(input.size).fill(i));
    return { blocks: keep.length };
  },
  // Fill the heap to `headroom` bytes below the limit, then do ordinary
  // work, so the refused allocation falls on a different step each time.
  'heap.work': (input) => {
    let lo = 0, hi = 32 << 20, keep = null;
    while (hi - lo > 16) {
      const mid = (lo + hi) >> 1;
      keep = null;
      try { keep = new ArrayBuffer(mid); lo = mid; } catch { hi = mid; }
    }
    keep = null;
    keep = new ArrayBuffer(Math.max(0, lo - input.headroom));
    class Row { constructor(id) { this.id = id; this.label = `row ${id}`; } }
    const rows = [1, 2, 3, 4, 5, 6, 7, 8].map(id => new Row(id)).filter(row => row.id % 2);
    const text = JSON.stringify(rows) + rows.map(row => row.label).join('|');
    const found = [...text.matchAll(/row (\d)/g)].map(match => match[1]);
    let error;
    try { throw new Error(`stop ${found.length}`); } catch (caught) { error = caught.stack; }
    try { new Function('return 1'); } catch {}
    return { found: found.length, error: typeof error };
  },
};
"#;

/// Error texts that name a reached limit. QuickJS reports an exception it
/// could not describe, for example after the heap ran out while it built
/// the error, as "Exception generated by QuickJS".
const LIMIT_ERRORS: [&str; 6] = [
    "exceeded its 16 MiB heap",
    "out of memory",
    "Exception generated by QuickJS",
    "Maximum call stack size exceeded",
    "interrupted",
    "deadline exceeded",
];

fn page(bytes: usize) -> String {
    let row = "<tr><td><a class=\"title\" href=\"/roms/game-12345\">Some Game Title (USA) v1.2</a></td><td>pico8 cart 42</td></tr>\n";
    row.repeat(bytes / row.len() + 1)
}

fn provider_input(text: &str) -> String {
    serde_json::json!({
        "query": "game",
        "responses": [{"status": 200, "ok": true, "url": "https://example.invalid/", "headers": {}, "text": text}],
    })
    .to_string()
}

/// JSON whose parsed form is far larger than its text: about 1.3 million
/// empty values in under 4 MiB. The heap runs out inside the input parse.
fn parse_exhausting_inputs() -> [String; 4] {
    [
        format!("{{\"items\":[{}[]]}}", "[],".repeat(1_300_000)),
        format!("{{\"items\":[{}{{}}]}}", "{},".repeat(1_300_000)),
        format!("{{\"items\":[{}0]}}", "0,".repeat(1_900_000)),
        format!("{{\"items\":[{}\"\"]}}", "\"a\",".repeat(900_000)),
    ]
}

struct Calls {
    snapshot: SourceSnapshot,
    count: usize,
}

impl Calls {
    fn new() -> Self {
        Self {
            snapshot: SourceSnapshot::plugin(PLUGIN).expect("limits plugin"),
            count: 0,
        }
    }

    /// One call. It must end as a result or as a limit error.
    fn call(&mut self, operation: &str, input: &str) -> Result<serde_json::Value, String> {
        self.count += 1;
        match call_plugin_operation_bounded(&self.snapshot, operation, input, PROVIDER_INPUT_BOUND)
        {
            Ok(output) => Ok(serde_json::from_str(&output).expect("result is JSON")),
            Err(failure) => {
                let message = failure.to_string();
                assert!(
                    LIMIT_ERRORS.iter().any(|limit| message.contains(limit)),
                    "{operation} ended with an error that names no limit: {message}"
                );
                Err(message)
            }
        }
    }

    /// An ordinary call after the limits still gets its ordinary result.
    fn assert_still_usable(&mut self) {
        let result = self
            .call("page.parse", &provider_input(&page(4_000)))
            .expect("ordinary call after limit errors");
        assert_eq!(result["rows"][0]["href"], "/roms/game-12345");
    }

    /// The near-limit calls that end as ordinary errors on the bundled engine.
    fn near_limit_round(&mut self, large_page: &str, parse_exhausting: &[String]) {
        self.call("page.parse", large_page).ok();
        for input in parse_exhausting {
            assert!(self.call("items.count", input).is_err());
        }
        for depth in [5_000, 100_000] {
            let error = self
                .call("stack.recurse", &format!("{{\"depth\":{depth}}}"))
                .unwrap_err();
            assert!(
                error.contains("Maximum call stack size exceeded"),
                "{error}"
            );
        }
        assert!(self
            .call("heap.hold", "{\"blocks\":1000,\"size\":100000}")
            .is_err());
        assert!(self
            .call("heap.hold", "{\"blocks\":100000,\"size\":10}")
            .is_err());
    }
}

#[test]
fn every_call_at_a_limit_ends_as_a_result_or_a_limit_error() {
    let mut calls = Calls::new();
    let large_page = provider_input(&page(3_900_000));
    let parse_exhausting = parse_exhausting_inputs();
    for _ in 0..3 {
        calls.near_limit_round(&large_page, &parse_exhausting);
    }
    let small = calls
        .call("page.parse", &provider_input(&page(200_000)))
        .expect("200 KB page parses within the limits");
    assert!(small["count"].as_u64().unwrap() > 1_000);
    assert_eq!(
        calls.call("stack.recurse", "{\"depth\":200}").unwrap()["depth"],
        200
    );
    let started = Instant::now();
    let error = calls.call("deadline.spin", "null").unwrap_err();
    assert!(error.contains("interrupted"), "{error}");
    assert!(started.elapsed() < Duration::from_secs(3));
    calls.assert_still_usable();
}

/// Run `name`'s work in a child process. The child must exit normally
/// within `limit`; a signal or a hang fails the parent test.
fn run_isolated(name: &str, limit: Duration) {
    let mut child = Command::new(std::env::current_exe().unwrap())
        .args([
            "--exact",
            name,
            "--include-ignored",
            "--nocapture",
            "--test-threads=1",
        ])
        .env(CHILD, "1")
        .spawn()
        .expect("spawn child test process");
    let started = Instant::now();
    loop {
        if let Some(status) = child.try_wait().unwrap() {
            assert!(
                status.signal().is_none(),
                "{name} ended the process abnormally: {status}"
            );
            assert!(status.success(), "{name} failed: {status}");
            return;
        }
        if started.elapsed() > limit {
            child.kill().ok();
            child.wait().ok();
            panic!("{name} did not end within {limit:?}");
        }
        std::thread::sleep(Duration::from_millis(50));
    }
}

/// Heap exhaustion at every step of ordinary plugin work: object and array
/// creation, JSON, regex matching, an error backtrace and an attempt to
/// compile code. With rquickjs 0.9 this sweep, with `new Function` as the
/// work, ended in SIGSEGV.
#[test]
#[ignore = "about 50 s: 4,000 calls; runs its work in a child process"]
fn filling_the_heap_ends_as_an_error() {
    if std::env::var_os(CHILD).is_none() {
        return run_isolated(
            "filling_the_heap_ends_as_an_error",
            Duration::from_secs(300),
        );
    }
    let mut calls = Calls::new();
    for headroom in (0..16_000).step_by(4) {
        calls
            .call("heap.work", &format!("{{\"headroom\":{headroom}}}"))
            .ok();
    }
    calls.assert_still_usable();
}

/// Plugin calls run on Tokio blocking threads, which have 2 MiB stacks.
const CALL_THREAD_STACK: usize = 2 * 1024 * 1024;

/// Recursion up to the 1 MiB QuickJS stack limit works, and every depth
/// across the limit ends as a result or as a stack error on a 2 MiB thread.
/// The exact depth depends on frame sizes, so on the compiler and its
/// hardening flags: in a debug `korrid-test` build on x86_64 the limit stops
/// plain recursion after 1,000 levels and recursion through `map` callbacks
/// after 294, while the `korrid-check` development shell stops them after
/// 580 and 175. A 512 KiB limit stopped them after 495 and 145 in the first
/// build. The floors below sit under every measured 1 MiB depth and above
/// the old 512 KiB depths in the `korrid-check` shell.
#[test]
fn recursion_across_the_stack_limit_ends_as_an_error() {
    if std::env::var_os(CHILD).is_none() {
        return run_isolated(
            "recursion_across_the_stack_limit_ends_as_an_error",
            Duration::from_secs(120),
        );
    }
    std::thread::Builder::new()
        .stack_size(CALL_THREAD_STACK)
        .spawn(|| {
            let mut calls = Calls::new();
            for (operation, floor, across) in [
                ("stack.recurse", 450, (50..=3_000).step_by(10)),
                ("stack.map", 130, (10..=1_000).step_by(5)),
            ] {
                let mut deepest = 0;
                let mut stopped = 0;
                for depth in across {
                    match calls.call(operation, &format!("{{\"depth\":{depth}}}")) {
                        Ok(result) => {
                            assert_eq!(result["depth"], depth, "{operation} at depth {depth}");
                            if stopped == 0 {
                                deepest = depth;
                            }
                        }
                        Err(error) => {
                            assert!(
                                error.contains("Maximum call stack size exceeded"),
                                "{operation} at depth {depth}: {error}"
                            );
                            stopped += 1;
                        }
                    }
                }
                eprintln!("{operation}: deepest working depth {deepest}");
                assert!(stopped > 0, "{operation} never reached the stack limit");
                assert!(
                    deepest >= floor,
                    "{operation} stopped at {deepest}, below the floor {floor}"
                );
            }
            calls.assert_still_usable();
        })
        .expect("spawn a 2 MiB call thread")
        .join()
        .unwrap();
}

/// A regular expression that backtracks without end must stop at the
/// deadline like any other plugin code.
#[test]
fn catastrophic_backtracking_reaches_the_deadline() {
    if std::env::var_os(CHILD).is_none() {
        return run_isolated(
            "catastrophic_backtracking_reaches_the_deadline",
            Duration::from_secs(60),
        );
    }
    let mut calls = Calls::new();
    let started = Instant::now();
    let error = calls
        .call(
            "page.backtrack",
            &provider_input(&format!("{}!", "a".repeat(40))),
        )
        .unwrap_err();
    assert!(error.contains("interrupted"), "{error}");
    assert!(started.elapsed() < Duration::from_secs(3));
    calls.assert_still_usable();
}

/// The long variant: more than 10,000 calls near the limits in one process.
#[test]
#[ignore = "long variant, about 140 s; runs its work in a child process"]
fn ten_thousand_near_limit_calls_keep_the_process_running() {
    if std::env::var_os(CHILD).is_none() {
        return run_isolated(
            "ten_thousand_near_limit_calls_keep_the_process_running",
            Duration::from_secs(3600),
        );
    }
    let mut calls = Calls::new();
    let large_page = provider_input(&page(3_900_000));
    let parse_exhausting = parse_exhausting_inputs();
    while calls.count < 10_000 {
        calls.near_limit_round(&large_page, &parse_exhausting);
        for headroom in (0..2_000).step_by(16) {
            calls
                .call("heap.work", &format!("{{\"headroom\":{headroom}}}"))
                .ok();
        }
    }
    calls.assert_still_usable();
    eprintln!("{} calls near the limits", calls.count);
}

/// QuickJS's parser does not survive every refused allocation, so plugin
/// code cannot compile source at run time. Every route throws; existing
/// functions and `instanceof Function` keep working.
#[test]
fn plugins_cannot_generate_code_at_run_time() {
    let probe = r#"
        const refused = route => { try { route(); return 'compiled'; } catch (error) { return error instanceof EvalError ? 'refused' : String(error); } };
        const routes = () => ({
            eval: typeof eval,
            evalCall: refused(() => globalThis.eval('1')),
            newFunction: refused(() => new Function('return 1')),
            callFunction: refused(() => Function('return 1')),
            reflectConstruct: refused(() => Reflect.construct(Function, ['return 1'])),
            functionConstructor: refused(() => (function () {}).constructor('return 1')),
            asyncFunction: refused(() => (async function () {}).constructor('return 1')),
            generatorFunction: refused(() => (function* () {}).constructor('yield 1')),
            asyncGeneratorFunction: refused(() => (async function* () {}).constructor('yield 1')),
            instanceOf: (() => 1) instanceof Function && (async () => 1) instanceof Function && class {} instanceof Function,
            sameConstructor: (function () {}).constructor === Function,
            ordinary: [1, 2, 3].map(n => n * 2).reduce((a, b) => a + b, 0) + Math.max.apply(null, [1, 4]) + ((a, b) => a - b).call(null, 9, 3) + ((a) => a).bind(null, 5)(),
        });
    "#;
    let expected = serde_json::json!({
        "eval": "undefined",
        "evalCall": "TypeError: not a function",
        "newFunction": "refused",
        "callFunction": "refused",
        "reflectConstruct": "refused",
        "functionConstructor": "refused",
        "asyncFunction": "refused",
        "generatorFunction": "refused",
        "asyncGeneratorFunction": "refused",
        "instanceOf": true,
        "sameConstructor": true,
        "ordinary": 27,
    });
    // At module evaluation, in the declaration.
    let declaration = korrid::script::eval_plugin_ts(&format!(
        "{probe} export const name = 'sealed'; export const config = routes();"
    ))
    .unwrap();
    let declaration: serde_json::Value = serde_json::from_str(&declaration).unwrap();
    assert_eq!(declaration["config"], expected);
    // In an operation call.
    let mut calls = Calls {
        snapshot: SourceSnapshot::plugin(&format!(
            "{probe} export const name = 'sealed'; export const handlers = {{'routes': routes}};"
        ))
        .unwrap(),
        count: 0,
    };
    assert_eq!(calls.call("routes", "null").unwrap(), expected);
}
